/* 辅助：数组去重 + 随机抽一个未用过的；全部用光则回退到全量随机 */
function drawOne(deck, usedSet) {
  const remain = deck.filter(q => !(q.id && usedSet.has(q.id)));
  const pool = remain.length ? remain : deck;
  const picked = pool[Math.floor(Math.random() * pool.length)];
  if (picked && picked.id) usedSet.add(picked.id);
  return picked;
}

/* 数组去重（用于弹窗列出可选题目）：filter 掉已用过的 */
function remainList(deck, usedSet) {
  return deck.filter(q => !(q.id && usedSet.has(q.id)));
}

